#!/usr/bin/env python3
"""Generate the two schematic testbenches, so they cannot drift apart.

They are rebuilt rather than patched.  The originals drove the amplifier with
one source sitting between INN and INP while INP was held fixed, which moves
the common mode by half the differential swing: test2.sch read 40.1 dB where
the standalone bench read 36.2 dB on the same circuit.  Two testbenches for one
amplifier must not report two gains, so both now use the same stimulus:

    VD  d   0                 the differential signal, referred to ground
    VCM cm  0                 the common mode
    EIP INP cm d 0  0.5       INP = cm + d/2
    EIN INN cm d 0 -0.5       INN = cm - d/2

Connectivity is by labels placed exactly on the pins - no wires, so nothing can
be a grid step away from what it looks like it touches (which is how VSS came
to be floating in the first version of test.sch).
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import measure

HERE = os.path.dirname(os.path.abspath(__file__))
DESIGN = os.path.dirname(HERE)

HEAD = """v {{xschem version=3.4.8RC file_version=1.3
* {title}
*
* Generated by sim/make_testbench.py - do not edit by hand, regenerate.
}}
G {{}}
K {{}}
V {{}}
S {{}}
E {{}}
"""

# pin offsets, read off the symbols
VS_P, VS_M = (0, -30), (0, 30)
E_P, E_M, E_CP, E_CM = (0, -30), (0, 30), (-40, -20), (-40, 20)


def lab(x, y, name, rot=0):
    return "C {devices/lab_pin.sym} %d %d %d 0 {name=%s lab=%s}\n" % (
        x, y, rot, name, name)


def gnd(x, y, name):
    return "C {devices/gnd.sym} %d %d 0 0 {name=%s lab=0}\n" % (x, y, name)


def vsource(x, y, name, value, net):
    """A source from `net` down to ground."""
    s = 'C {devices/vsource.sym} %d %d 0 0 {name=%s value="%s" savecurrent=false}\n' % (
        x, y, name, value)
    s += lab(x + VS_P[0], y + VS_P[1], net)
    s += gnd(x + VS_M[0], y + VS_M[1], "g" + name)
    return s


def vcvs(x, y, name, gain, out, ref, ctrl):
    s = "C {devices/vcvs.sym} %d %d 0 0 {name=%s value=%s}\n" % (x, y, name, gain)
    s += lab(x + E_P[0], y + E_P[1], out)
    s += lab(x + E_M[0], y + E_M[1], ref)
    s += lab(x + E_CP[0], y + E_CP[1], ctrl)
    s += gnd(x + E_CM[0], y + E_CM[1], "g" + name)
    return s


def build(dut_sym, dut_pins, sources, nodes, stages, title, models_lib="best"):
    """dut_pins: {pin name: (dx, dy)} from the symbol; sources: list of tuples."""
    dx, dy = 700, -400
    out = HEAD.format(title=title)
    out += "C {%s} %d %d 0 0 {name=x1}\n" % (dut_sym, dx, dy)
    for pin, (ox, oy) in dut_pins.items():
        x, y = dx + ox, dy + oy
        out += gnd(x, y, "gvss") if pin == "VSS" else lab(x, y, pin)

    x = 150
    for kind, name, a, b in sources:
        if kind == "v":
            out += vsource(x, -650, name, a, b)
            x += 120
    out += vcvs(1000, -650, "EIP", "0.5", "INP", "cm", "d")
    out += vcvs(1200, -650, "EIN", "-0.5", "INN", "cm", "d")

    out += ('C {devices/code_shown.sym} 20 -160 0 0 {name=MODELS '
            'only_toplevel=true\nformat="tcleval( @value )"\nvalue="\n'
            ".include $::IGZO_MODELS/design.ngspice\n"
            ".lib $::IGZO_MODELS/igzo_mmm_lab.ngspice %s\n\"}\n" % models_lib)
    out += ('C {devices/code_shown.sym} 1500 -700 0 0 {name=NGSPICE '
            'only_toplevel=true\nvalue="\n%s"}\n'
            % measure.block(nodes, stages, plots=True, src="VD", vin="v(d)"))
    out += ('C {devices/title.sym} 160 -30 0 0 '
            '{name=l5 author="UCI/INRF - MMM Lab"}\n')
    return out


OPAM2_PINS = {"VDD": (150, -20), "INP": (-150, -20), "OUT": (150, 0),
              "INN": (-150, 0), "VSS": (150, 20)}
OPAM_PINS = {"VDD": (150, -30), "OUT": (150, -10), "INN": (-150, -30),
             "INP": (-150, -10), "BIAS": (150, 10), "VSS": (150, 30)}
# the self-biased variant has no BIAS pin - that is the point of it
BIASED_PINS = {k: v for k, v in OPAM_PINS.items() if k != "BIAS"}

if __name__ == "__main__":
    import install_measure as im

    open(os.path.join(DESIGN, "test2.sch"), "w").write(build(
        "MMM-LAB DESIGN/OPAM/OPAM2.sym", OPAM2_PINS,
        [("v", "V1", "8", "VDD"), ("v", "VCM", "3.2", "cm"),
         ("v", "VD", "0 AC 1 SIN(0 0.005 1)", "d")],
        im.OPAM2_NODES, [],
        "OPAM2 open-loop testbench - Zysset topology, all-enhancement IGZO"))
    print("wrote test2.sch")

    open(os.path.join(DESIGN, "test.sch"), "w").write(build(
        "MMM-LAB DESIGN/OPAM/OPAM.sym", OPAM_PINS,
        [("v", "V1", "8", "VDD"), ("v", "VCM", "4.00", "cm"),
         ("v", "VD", "0 AC 1 SIN(0 0.005 1)", "d"),
         ("v", "V2", "1.25", "BIAS")],
        im.OPAM_NODES, im.OPAM_STAGES,
        "OPAM open-loop testbench - Zhao topology, cross-coupled + bootstrap"))
    print("wrote test.sch")

    open(os.path.join(DESIGN, "test_biased.sch"), "w").write(build(
        "MMM-LAB DESIGN/OPAM/OPAM_BIASED.sym", BIASED_PINS,
        [("v", "V1", "8", "VDD"), ("v", "VCM", "2.0", "cm"),
         ("v", "VD", "0 AC 1 SIN(0 0.005 1)", "d")],
        im.OPAM_NODES + ["x1.BIAS"], im.OPAM_STAGES,
        "OPAM with the bias generated on chip - no BIAS pin, no per-corner trim"))
    print("wrote test_biased.sch")
